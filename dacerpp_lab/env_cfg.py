    # 이력: 0.1/0.26 에서는 클램프 상한(0.4/step) 탓에 깊은 드리프트(실측 maxβ
    # p50=43°, 급코너를 그립한계 5.6 대비 7.5m/s 통과)가 순이익(벌점 2.4 <
    # 시간이득 ~4)이라 '드리프트 코너링' 전략이 잔존 -> 0.3/0.21 로 상향
