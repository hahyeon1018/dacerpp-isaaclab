@configclass
class TireModelCfg:
    """해석적 타이어 힘 모델 (동적 자전거 모델 + 포화 슬립 곡선).

    왜 접촉 타이어가 아닌가: PhysX 강체 접촉은 바퀴 회전 ω>60rad/s(차속 ~3m/s)
    에서 접촉 솔버가 회전 바디에 매 스텝 가짜 제동 각임펄스를 만들며 횡그립이
    μg 의 5~10%로 붕괴한다 (scripts/characterize_car.py 실측; 충돌형상/솔버
    반복수/물리주파수/CPU·GPU 전부 교차 검증 후 배제). 실타이어 횡력은 고무
    변형(슬립각-횡력 곡선)에서 나오므로 강체 Coulomb 접촉으로는 원리적으로
    표현되지 않는다 — PhysX Vehicle SDK, f1tenth_gym 과 동일하게 슬립 기반
    힘을 섀시에 직접 인가한다(수직 지지는 바퀴 접촉이 담당, 지면 마찰은 0).

    ★ sim2real: 실차 (조향각, 속도) -> 요레이트/횡가속 응답을 측정해
    mu / alpha_char / k_drive / f_drive_max 를 시스템 식별으로 맞출 것.
    scripts/characterize_car.py 가 시뮬 쪽 응답 맵을 출력한다.
    """
    mu: float = 1.05               # 공칭 마찰 (mu_range=None 일 때/평가·특성측정용)
    # 지면 마찰 도메인 랜덤화 — 대회 규정 확정 반영(2026-07-21):
    #   "BEXCO 제2전시장 3층 Hall 5A: 경화 콘크리트 + 우레탄 코팅 마감.
    #    일반 아스팔트 대비 마찰계수가 현저히 낮고 표면이 매끄러움"
    # 고무-노면 건조 마찰계수 기준값: 아스팔트 0.8~1.0, 맨 콘크리트 0.7~0.9,
    # 폴리우레탄 도막 마감 0.45~0.75(도막이 표면 요철을 메워 매끄러움).
    # RC 소프트 컴파운드 타이어는 접지면이 작아도 컴파운드가 무르므로 상단 근처.
    # -> U(0.55, 0.95) 로 추첨. 하한은 먼지/이형제 잔류, 상한은 청소 직후 상태.
    # 이력: 1.2(카펫)→0.65(경화콘크리트,2026-07-21)→0.75(2026-07-22)→0.65(2026-08-07)
    #   →2026-08-07 상향((0.45,0.85)→(0.7,1.1), 중앙 0.65→0.90): 사용자 재지시 —
    #   실차가 코너에서 바깥벽에 붙어 과보수 주행하는 게 '그립 부족 인식'으로 인한 것이라
    #   보고, 학습 그립을 높여 '지면에 잘 붙고 더 빠르게' 코너링(더 타이트한 라인)하도록
    #   유도. 0.7~1.1 = 청소된 도막~카펫 상단 대역.
    #   →2026-08-09 추가 상향((0.7,1.1)→(0.85,1.25), 중앙 0.90→1.05): 사용자 실험 지시
    #   — 그립을 한 단계 더 올려 코너 라인을 더 타이트/고속화. 슬립 벌점 완화와 세트로 실험.
    #   ★ 상한 1.25 는 카펫 상단 이상(고그립) 대역 — 실제 도막 그립보다 크게 높을 수 있어
    #   sim2real 언더스티어 위험이 커진다. 실차 확인 후 밴드 재수축 필요.
    # ★ sim2real 주의: 실제 도막 그립이 이보다 낮으면 정책이 그립을 과대평가해 오히려
    #   실차에서 언더스티어(바깥벽 밀착)가 재발할 수 있다 — 현장 practice 스키드패드로
    #   실측해 그 값 ±0.1 로 좁혀 재조정할 것.
    mu_range: tuple | None = (0.85, 1.25)
    alpha_char: float = 0.08       # 특성 슬립각(rad): F_y=-mu*N*tanh(alpha/alpha_char).
                                   # 선형 강성 = mu*N/alpha_char (≈15N/rad/N), 포화 ~9도
                                   # ★ 미확정 — 스키드패드 sub-limit 곡선으로 피팅
    # ---- 실측 (2026-07-16, 코너웨이트 총 3940.6g / 앞 2161.0g 55% / 뒤 1779.6g 45%) ----
    # ★2026-08-12 실차 총중량 +300g -> 3.94 = 4.24kg.
    #   반드시 assets/f1tenth/f1tenth.urdf 의 base_link mass(3.441 -> 3.741)와 세트로
    #   바꾸고 USD 를 재생성해야 한다. 여기는 해석 타이어 모델의 수직하중(Nf/Nr) 계산용,
    #   URDF/USD 는 PhysX 운동 적분용이라 어긋나면 '4.24kg 의 그립으로 3.94kg 를 가속'
    #   하는 비물리가 된다. 재생성 절차는 이 파일 하단 주석 또는 README 참조.
    mass: float = 4.24             # 하중 계산용(kg) — 운동 적분은 PhysX(USD) 질량 사용
    com_height: float = 0.07       # 무게중심 높이(m): 종방향 하중이동 (미실측, 추정 유지)
    # ★lf/lr 은 '무게 배분비가 변하지 않았다'는 가정 하에 그대로 둔다(증가분이 앞뒤로
    #   기존 비율대로 분산된 경우). 증가분이 한쪽에 몰렸다면 아래 값으로 교체할 것 —
    #   코너웨이트를 다시 재는 것이 가장 확실하다(앞/뒤 축하중 g 단위).
    #     전부 뒤축(예: 뒷부분 감지 박스/배터리): lf=0.162, lr=0.168
    #     전부 앞축                             : lf=0.139, lr=0.191
    #   CoM 이 뒤로 갈수록(lf 증가) 오버스티어 경향이 커지므로 무시할 차이가 아니다.
    lf: float = 0.149              # CoM -> 앞축 거리(m) = L(0.33) x 뒤축하중비(0.4516)
    lr: float = 0.181              # CoM -> 뒤축 거리(m) = L(0.33) x 앞축하중비(0.5484)
    k_drive: float = 40.0          # ESC 속도서보 게인 N/(m/s): F_x = k*(v_cmd - vx)
                                   # (VESC speed 모드 확인됨. ★ 게인/상한은 직선
                                   #  풀스로틀 가속 로그로 피팅할 것 — 측정 지시서 [M4])
    # 모터 특성이라 질량과 무관하게 유지. 대신 가속 한계가 5.6 -> 5.19 m/s² 로 낮아진다
    # (22.0N / 4.24kg). 코너 한계속 sqrt(μgR) 은 질량 무관이라 변하지 않는다 —
    # 이번 증량의 영향은 '가감속'과 '하중이동'에 국한된다.
    f_drive_max: float = 22.0      # 구동/제동력 상한(모터, N) ≈ 5.19 m/s² @4.24kg
                                   # (제동은 추가로 뒤축 마찰서클 μN_r 제한)
    c_roll: float = 0.015          # 구름저항 계수
    v_lat_taper: float = 0.3       # 저속 횡력 테이퍼(m/s): 정지 시 조향만으로
                                   # 횡력이 생기는 비물리 방지 (tanh(|vx|/v))


@configclass
class RacingCfg:
    """관측/행동/보상 파라미터 (업로드 racing_env.py 의 다중환경판)."""
    # 관측
    # 트랙 폭은 고정값이 아니라 TrackParams.width_min/width_max 의 가변 프로파일
    # (실 대회장 덕트 간격 1~5m). 이탈판정/보상/관측 정규화는 지역 half-width 사용.
    n_beams: int = 32
    scan_max_range: float = 10.0
    scan_fov: float = 2.356               # rad, 전방 ±135도
    # 전방 곡률/폭 예견 인덱스 (인덱스당 호길이 ~0.15m -> 0.75/2.25/4.5/9/13.5/18m).
    # 최원거리는 v_max 에서 최악 코너 한계속까지 '데드존 준수 제동(<=3.5m/s^2)'
    # 거리를 커버해야 제때 감속이 관측 가능하다.
    # (구 최원거리 9m 는 부족 -> 감속 시점을 볼 수 없어 +90 추가. obs_dim 52->54)
    # ★2026-08-17 +120 추가 (obs_dim 58->60). 근거(측정):
    #   기존 최원거리 13.5m 는 마찰 하향(mu_range 0.45~0.75) 후 부족해졌다.
    #   lobby_0812 최악 코너는 R=0.412m 이고 mu=0.6 에서 한계속 sqrt(mu*g*R)=1.56m/s
    #   인데, 10m/s -> 1.56m/s 를 3.5m/s^2 로 줄이려면 14.0m 가 필요하다. 즉 정책이
    #   그 코너를 '보는 순간' 이미 제동이 늦는다 — 실차 '늦게 꺾음'의 유력 원인.
    #   18m 면 여유 4m 가 생긴다.
    # ★교체(90->120)가 아니라 '추가'인 이유: 교체하면 13.5m 해상도를 잃는다.
    #   곡률과 폭이 이 오프셋을 공유하므로(width_offsets=(0,)+curv_lookahead)
    #   원소 1개 추가 = 관측 +2차원이다.
    # ★상한 근거: comp 트랙 128종 표본의 랩 길이는 min 41.8 / 중앙 55.1m.
    #   120idx=18.0m 는 최단 랩의 43%로 안전하지만, 150idx=22.5m 는 128종 중 22종에서
    #   랩의 절반을 넘어 '앞'이 아니라 '뒤에서 오는 구간'을 보게 된다. 130 이상 금지.
    # ★배포 동반 변경: race_stack rl_controller.yaml 의 curv_lookahead 도 같은 목록으로.
    #   (노드는 차원을 계산해서 검사하므로 안 맞으면 시작 시 에러로 막힌다 — 조용히
    #    틀리지는 않지만, 목록을 안 고치면 새 체크포인트가 아예 안 뜬다.)
    curv_lookahead: Sequence[int] = (5, 15, 30, 60, 90, 120)
    # 전방 곡률 관측 클립(±). ★2026-08-12 2.0 -> 3.0.
    # 근거(측정): 신규 연습 맵 lobby_0811 은 '로드 후' |κ|max 2.78, 0812 는 2.43 이라
    # ±2 클립이 랩 위치의 9.4%(0811)에서 곡률 채널을 포화시켰다. 그 구간에서 정책이
    # 보는 최소 반경은 0.50m, 실제는 0.36m — 28% 과소평가다. 즉 정책은 'κ=2.0 코너'와
    # '헤어핀'을 관측상 구분할 수 없었고, 20260810 가중치를 실제 형상 위에서 조사한
    # 결과 그 지점에서 필요 조향각의 70%만 명령했다(0.273 vs 0.391 rad) = 실차의
    # '안 꺾고 직진' 증상. 3.0 은 재생성된 comp 세트의 |κ|max 상한 2.85 를 포화 없이 담는다.
    # ★ 관측 스케일 변경 = 체크포인트 비호환(재학습 필수).
    # ★ 배포 동반 변경: race_stack rl_controller.yaml 의 curv_clip 도 같은 값으로.
    #    체크포인트와 반드시 세트로 바꿀 것 — 구 체크포인트에 3.0 을 주면 분포 밖 입력이 된다.
    curv_clip: float = 3.0
    # v_max 변경 시 연쇄 확인: car_cfg 의 바퀴 velocity_limit_sim(>= v_max/0.05)
    # 과 max_linear_velocity(>= v_max+여유), 그리고 관측 정규화(speed/v_max)가
    # 바뀌므로 재학습 필요.
    # 12 는 랩 60m 트랙에서 제동거리(9m+)가 관측 예견을 초과해 벽 충돌 유발 -> 10.
    # ★ 실차 v_max 미확정: VESC speed_to_erpm_gain=3550 (속도서보 모드 확인됨,
    #   v[m/s] = erpm/3550) — 최대 ERPM 설정값 또는 직선 최고속 로그로 확정할 것.
    v_max: float = 10.0
    v_min: float = 1.0                    # 완전 정지 불가(최저 순항) — 브레이크체크 완화
    # 실측(2026-07-16): 기계 한계 0.44 rad, 과열 방지를 위해 명령 상한 0.42 권장(사용자).
    max_steering_angle: float = 0.42
    wheel_radius: float = 0.06            # 실측 (r=6cm, 폭 4.5cm)
    # 스캔 (벽 레이캐스트: 실제 F1TENTH 덕트 벽 대응)
    wall_offset: float = 0.0              # 덕트 내측면이 트랙 경계보다 바깥이면 +
    # 레이캐스트 세그먼트 윈도(중심선 인덱스 ± 개수). 트랙 축소(반경 9.33m) 후
    # 인덱스당 호길이 ~0.15m -> ±96 ≈ ±14m 가 스캔범위(10m) 내 반대편 벽까지 커버.
    raycast_half_window: int = 96
    # ---- 섹터 축약 모사 (2026-08-12) ----
    # 실차 의사 스캔은 빔 '각도'로 레이캐스트하는 게 아니라, 폭 2*fov/(n_beams-1)
    # = 8.71° 섹터 안에 들어온 LiDAR 점들의 '최소 거리'를 쓴다(scan_builder.build).
    # 섹터 min 은 경사벽에서 중심 빔보다 구조적으로 짧게 읽힌다 — 실제 연습 맵
    # 형상에서 측정한 (섹터min - 정확빔) 편향은 평균 -0.21m, p5 -0.90m 이고,
    # 빔의 54%가 학습 스캔 노이즈(0.035m)보다 큰 오차를 갖는다. scan_noise_std 는
    # 영평균이라 이 '편향'을 모사하지 못하고, scan_angle_jitter(±0.5°)는 섹터
    # 반폭(4.36°)의 12%에 불과했다. -> 빔마다 섹터를 가로지르는 여러 레이를 쏘고
    # 최소값을 취해 실차와 같은 편향을 학습 분포에 넣는다.
    # 비용: 레이캐스트 텐서가 이 배수만큼 커진다(3 -> 약 3배 VRAM). 1 = 구 동작(단일 레이).
    scan_sector_rays: int = 3
    # ---- 근거리 스캔 사각지대 (2026-08-17, 실차 scan_builder.self_box 모사) ----
    # 실차 의사 스캔은 자차 전장품 반사를 지우려고 base_link 기준 박스
    # [x_min, x_max, |y|] 안의 점을 '전부 버린다'(scan_builder.ingest_cloud).
    # 그래서 전방 ±20°(=atan2(0.20,0.55)) 빔은 0.55m 미만을 원리적으로 못 읽고,
    # 더 중요한 것은 '클립'이 아니라 '삭제'라는 점이다 — 벽이 0.3m 앞에 있으면
    # 그 점들이 사라지고 그 방위각 섹터에 남는 점이 없어 빔이 max_range(10m)로
    # 읽힌다. 즉 실차 스캔에는 근거리에 '구멍'이 생기는데 학습 레이캐스트는
    # 0 까지 정확히 읽어 이 실패 모드를 한 번도 보지 못했다.
    # -> 레이캐스트 결과 중 이 박스 안에 떨어지는 히트를 max_range 로 되돌려
    #    같은 구멍을 학습 분포에 넣는다. None = 끔(구 동작).
    # ★ 값은 race_stack rl_controller.yaml 의 self_box 와 반드시 동일하게 유지할 것.
    scan_blind_box: tuple | None = (-0.40, 0.55, 0.20)
    # ---- 관측 기준점 오프셋 (2026-08-17, sim2real) ----
    # 실차 관측은 전부 base_link 기준이고 이 차의 base_link 는 '뒤축'이다
    # (EKF pose 가 base_link, scan_builder 도 점을 base_link 로 옮겨 그 원점에서
