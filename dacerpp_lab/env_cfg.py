    # k_slip 커리큘럼: 신규 학습 초기의 강슬립벌점은 미숙련 정책의 속도 상승
    # 경로를 차단해 저속 국소최적에 가둔다(20260712 실측: v 3.2 함정).
    # v0 에서 시작해 ramp_steps 에 걸쳐 목표값(k_slip)으로 선형 상승.
    # train.py 의 set_curriculum_progress(it) 가 갱신, 0 이면 비활성(항상 k_slip).
    k_slip_v0: float = 0.1
