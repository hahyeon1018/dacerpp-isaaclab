    # ---- 스핀/슬라이드 (해석 타이어에서 제동+조향 콤바인드가 뒤축 그립을 잠식해
    # 브레이크 오버스티어 스핀이 실제로 발생 — 실측: 스핀 직전 0.5초 감속 -10.5m/s²) ----
    # 사이드슬립 데드존 벌점: |β|=atan2(|vy|,|vx|) 초과분 2차 (스텝당 최대 k_slip*4).
