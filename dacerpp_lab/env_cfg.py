    # 관측 정규화는 항상 /v_max 라 커리큘럼과 무관(관측 비정상성 없음).
    # curriculum_steps=0 이면 비활성(test.py 등은 호출 안 하므로 항상 v_max).
    curriculum_v0: float = 6.0
    curriculum_steps: int = 300_000
    # 관측 차원
    n_opp_feats: int = 5
    # 차량 동역학 관측 정규화 (2026-07-14 추가: 요레이트+횡속도 — 실차 IMU 자이로와
